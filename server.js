const express = require('express');
const fs = require('fs');
const path = require('path');
const bcrypt = require('bcryptjs');
const cors = require('cors');
const crypto = require('crypto');

const app = express();
const PORT = process.env.PORT || 3000;
const DB_FILE = path.join(__dirname, 'users.json');

app.use(cors({
  origin: true,
  methods: ['GET', 'POST', 'DELETE', 'OPTIONS'],
  allowedHeaders: ['Content-Type']
}));
app.use(express.json());

function readDB() {
  try {
    if (!fs.existsSync(DB_FILE)) return {};
    const data = JSON.parse(fs.readFileSync(DB_FILE, 'utf8'));
    return data && typeof data === 'object' ? data : {};
  } catch (err) {
    console.error('Database read error:', err.message);
    return {};
  }
}

function writeDB(data) {
  const tmp = `${DB_FILE}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(data, null, 2));
  fs.renameSync(tmp, DB_FILE);
}

function makeSessionId() {
  return `sess_${crypto.randomBytes(32).toString('hex')}`;
}

function cleanDeviceId(value) {
  const id = String(value || '').trim();

  // Device IDs generated by the HTML should be at least 16 chars.
  // Maximum length prevents oversized input.
  if (id.length < 16 || id.length > 256) return '';
  return id;
}

function normalizeUser(user) {
  if (!user || typeof user !== 'object') return user;

  let changed = false;

  if (!Object.prototype.hasOwnProperty.call(user, 'deviceId')) {
    user.deviceId = '';
    changed = true;
  }

  if (!Object.prototype.hasOwnProperty.call(user, 'deviceBoundAt')) {
    user.deviceBoundAt = null;
    changed = true;
  }

  if (!Object.prototype.hasOwnProperty.call(user, 'activeSession')) {
    user.activeSession = '';
    changed = true;
  }

  if (changed) return user;
  return user;
}

function prepareDB(db) {
  let changed = false;

  for (const username of Object.keys(db)) {
    const before = JSON.stringify(db[username]);
    db[username] = normalizeUser(db[username]);
    if (JSON.stringify(db[username]) !== before) changed = true;
  }

  if (changed) writeDB(db);
  return db;
}

async function seedDefaultUsers() {
  const db = prepareDB(readDB());
  let changed = false;

  const defaults = {
    uk0wme: { password: 'ilobyou', days: 300, role: 'admin' },
    ankit: { password: 'gupta', days: 30, role: 'user' },
    rajj: { password: 'rajj', days: 28, role: 'user' },
    john: { password: 'john7698', days: 28, role: 'user' }
  };

  for (const [username, cfg] of Object.entries(defaults)) {
    if (!db[username]) {
      db[username] = {
        password: await bcrypt.hash(cfg.password, 10),
        expiresAt: Date.now() + cfg.days * 24 * 60 * 60 * 1000,
        activeSession: '',
        deviceId: '',
        deviceBoundAt: null,
        role: cfg.role
      };
      changed = true;
    } else {
      const user = normalizeUser(db[username]);

      if (!user.role) {
        user.role = cfg.role;
        changed = true;
      }

      // Existing accounts with no deviceId become bound on their
      // first successful login after this version is deployed.
      if (!Object.prototype.hasOwnProperty.call(user, 'deviceId')) {
        user.deviceId = '';
        user.deviceBoundAt = null;
        changed = true;
      }
    }
  }

  if (changed) writeDB(db);
}

